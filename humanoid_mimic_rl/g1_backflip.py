"""G1 standing-backflip problem definition for ``flip_opt`` (mujoco + scipy, no JAX)."""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path

import mujoco
import numpy as np

from humanoid_mimic_rl import flip_dynamics as fd
from humanoid_mimic_rl import flip_opt, g1_model

ix = g1_model.joint_index

# Left/right-symmetric sagittal joint groups driven by the optimiser.
GROUPS: dict[str, tuple[int, ...]] = {
    "hip": (ix("left_hip_pitch_joint"), ix("right_hip_pitch_joint")),
    "knee": (ix("left_knee_joint"), ix("right_knee_joint")),
    "ankle": (ix("left_ankle_pitch_joint"), ix("right_ankle_pitch_joint")),
    "shoulder": (ix("left_shoulder_pitch_joint"), ix("right_shoulder_pitch_joint")),
    "waist": (ix("waist_pitch_joint"),),
}
# The waist pitch is free: held rigid it must accelerate the whole upper body
# with the pelvis and needed 10x its cap. Waist roll stays at 0: the motion is
# left/right symmetric, so roll cannot help. Elbows stay at the home pose.

# Spline knots (s); the first two and last two are pinned to the home pose.
KNOT_TIMES_S = np.array([0, 0.3, 0.55, 0.75, 0.9, 1.0, 1.1, 1.2, 1.3, 1.4, 1.5, 1.65, 1.85, 2.1, 2.5, 3.0])
DURATION_S = 3.0

# Hand-written starting point for the optimiser (rows: free knots 0.55 .. 2.1 s;
# columns: hip, knee, ankle, shoulder, waist pitch in rad) and take-off time.
INITIAL_KNOTS = np.array(
    [
        [-0.5, 1.0, -0.5, 0.6, 0.0],
        [-1.0, 1.8, -0.8, 1.0, 0.0],
        [-0.4, 0.8, -0.3, -1.0, 0.0],
        [-0.2, 0.3, 0.3, -2.5, 0.0],
        [-1.2, 1.6, 0.0, -2.0, 0.0],
        [-2.0, 2.4, 0.0, -1.2, 0.0],
        [-2.2, 2.5, 0.0, -1.0, 0.0],
        [-1.6, 1.9, -0.2, -0.8, 0.0],
        [-1.0, 1.4, -0.4, -0.5, 0.0],
        [-1.0, 1.7, -0.7, -0.2, 0.0],
        [-0.9, 1.6, -0.7, 0.0, 0.0],
        [-0.5, 0.9, -0.4, 0.2, 0.0],
    ]
)
INITIAL_TAKEOFF_S = 0.97

# Optimised parameters shipped with the repository (written by
# scripts/make_g1_backflip.py --optimize); the clip is rebuilt from them.
SOLUTION_PATH = Path(__file__).resolve().parent / "data" / "g1_backflip_solution.json"

LICENCE = (
    "Generated by trajectory optimisation in this repository (humanoid_mimic_rl/flip_opt.py) on the "
    "Unitree G1 model of MuJoCo Playground (Apache-2.0) / MuJoCo Menagerie unitree_g1 (BSD-3-Clause); "
    "contains no third-party motion data. Same licence as this repository."
)
SOURCE = "humanoid_mimic_rl.g1_backflip + flip_opt (ballistic flight, inverse-dynamics constrained)"


def load_model(assets: Mapping[str, bytes]) -> mujoco.MjModel:
    """Full-collision G1 with the flip-task servo stiffness (``g1_model.FLIP_SERVO_KP``)."""
    scene, full_assets = g1_model.full_collision_flat_scene(assets)
    model = mujoco.MjModel.from_xml_string(scene, assets=full_assets)
    g1_model.apply_servo_kp(model, g1_model.FLIP_SERVO_KP)
    return model


def floating_base(model: mujoco.MjModel) -> fd.FloatingBaseModel:
    feet = fd.FootGeometry(
        g1_model.FOOT_BODIES, g1_model.FOOT_SOLE_CENTRE_LOCAL_M, g1_model.FOOT_HALF_LENGTH_M, g1_model.FOOT_HALF_WIDTH_M
    )
    return fd.FloatingBaseModel(model, feet, g1_model.FLOOR_PAIR_GEOMS)


def make_problem(assets: Mapping[str, bytes], sample_rate_hz: float) -> flip_opt.FlipProblem:
    model = load_model(assets)
    setup = flip_opt.FlipSetup(
        groups=GROUPS,
        home_qpos=model.keyframe("home").qpos.copy(),
        knot_times_s=KNOT_TIMES_S,
        duration_s=DURATION_S,
        sample_rate_hz=sample_rate_hz,
        friction=g1_model.FOOT_FRICTION,
    )
    return flip_opt.FlipProblem(floating_base(model), setup)


def initial_params(problem: flip_opt.FlipProblem) -> np.ndarray:
    return problem.pack(INITIAL_KNOTS, INITIAL_TAKEOFF_S)


def save_solution(path: Path, x: np.ndarray, info: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"params": [float(v) for v in x], **info}, indent=2), encoding="utf-8")


def load_solution(path: Path) -> np.ndarray:
    return np.asarray(json.loads(path.read_text(encoding="utf-8"))["params"], dtype=np.float64)
